// 超立方体 (Tesseract) 4D投影
export const TESSERACT = {
  vertices: (() => {
    const v = [];
    for (let i = 0; i < 16; i++) {
      v.push([(i & 1) * 2 - 1, ((i >> 1) & 1) * 2 - 1, ((i >> 2) & 1) * 2 - 1, ((i >> 3) & 1) * 2 - 1]);
    }
    return v;
  })(),
  edges: (() => {
    const e = [];
    for (let i = 0; i < 16; i++) {
      for (let j = i + 1; j < 16; j++) {
        let diff = 0;
        for (let k = 0; k < 4; k++) if (((i >> k) & 1) !== ((j >> k) & 1)) diff++;
        if (diff === 1) e.push([i, j]);
      }
    }
    return e;
  })()
};
